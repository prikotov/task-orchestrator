<?php

declare(strict_types=1);

namespace TaskOrchestrator\Common\Component\Layout;

/**
 * Выбрасывается, когда layout-ресурс отсутствует и в host-проекте, и в пакете.
 *
 * Отсутствие обоих кандидатов означает повреждённый дистрибутив (битую сборку
 * PHAR/пакета): ресурс обязан существовать хотя бы в package root, иначе
 * приложение неработоспособно. Возврат несуществующего или предполагаемого
 * пути запрещён — запуск прерывается явным исключением.
 *
 * Диагностика намеренно безопасная: фиксированный текст без содержимого кеша
 * контейнера и без несуществующих абсолютных путей (утечка путей окружения
 * и мусор из кеша в сообщении не помогают диагностике); указывается только
 * относительный путь ресурса.
 */
final class LayoutResourceNotFoundException extends \RuntimeException
{
    public function __construct(string $relativeResourcePath)
    {
        parent::__construct(sprintf(
            'Ни host-, ни package-ресурс не найден — дистрибутив повреждён (ресурс: %s).',
            $relativeResourcePath,
        ));
    }
}
